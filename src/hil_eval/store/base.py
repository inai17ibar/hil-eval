from pathlib import Path
from typing import Protocol

from ..types import Item, ProjectConfig, Review, Status, ThresholdHistory


class ItemNotFoundError(LookupError):
    """Raised by ``save_review`` when the target item does not exist."""


class Store(Protocol):
    def ensure_project(
        self,
        name: str,
        *,
        threshold: float | None,
        target_miss_rate: float | None,
        audit_rate: float | None,
    ) -> ProjectConfig: ...
    def get_project(self, name: str) -> ProjectConfig | None: ...
    def list_projects(self) -> list[ProjectConfig]: ...
    def update_threshold(self, project: str, threshold: float) -> None: ...
    def save_item(self, item: Item) -> Item: ...
    def get_item(self, item_id: str) -> Item | None: ...
    def delete_item(self, item_id: str) -> bool: ...
    def list_items(
        self,
        project: str | None,
        *,
        status: Status | list[Status] | None = None,
        min_confidence: float | None = None,
        max_confidence: float | None = None,
        limit: int = 100,
        offset: int = 0,
        order: str = "asc",
    ) -> list[Item]: ...
    def count_items(
        self,
        project: str | None,
        *,
        status: Status | list[Status] | None = None,
        min_confidence: float | None = None,
        max_confidence: float | None = None,
    ) -> int: ...
    def save_review(self, review: Review) -> Review: ...
    def list_reviews(self, item_id: str) -> list[Review]: ...
    def list_reviewed(self, project: str) -> list[tuple[Item, Review]]: ...
    def add_threshold_history(self, entry: ThresholdHistory) -> ThresholdHistory: ...
    def apply_threshold_change(self, entry: ThresholdHistory) -> ThresholdHistory: ...
    def list_threshold_history(self, project: str) -> list[ThresholdHistory]: ...
    def put_blob(self, sha256: str, data: bytes, mime: str) -> str: ...
    def get_blob_path(self, sha256: str) -> Path | None: ...
